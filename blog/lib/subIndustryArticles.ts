const callout = (variant: "tip" | "caution" | "summary", title: string, text: string) => lx.block({ blockType: "callout", variant, title, text });
const checklist = (title: string, items: string[]) => lx.block({ blockType: "checklist", title, items: items.map((text) => ({ text })) });
const flow = (items: [string, string][]) => lx.block({ blockType: "flow", items: items.map(([label, text]) => ({ label, text })) });
const aiChat = (question: string, answer: string, sourceTitle: string, sourceSite: string) =>
  lx.block({ blockType: "aiChat", question, answer, sourceTitle, sourceSite });

// 받침이 있으면 a, 없으면 b 를 붙인다 — "환자는 / 고객은" 처럼 부르는 말에 맞춰 조사를 고른다
const josa = (word: string, a: string, b: string) => {
  const c = word.charCodeAt(word.length - 1);
  return word + (c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 ? a : b);
};

